"""Reproduce the tiny kitty policy from original synthetic behavior examples.

Training-only dependency: NumPy. The Windows app needs no Python, model runtime,
network, user data, or additional packages. This is imitation learning over an
original synthetic utility teacher, not a language model or an online service.
The generated two-layer tanh network has 378 parameters (3,024 float64 bytes).
"""
import os
os.environ.setdefault('OPENBLAS_NUM_THREADS', '1')
from pathlib import Path
import numpy as np

SEED = 20261031
NAMES = ('Watch', 'Walk', 'Chase', 'Swat', 'SmackPanel', 'Zoomies', 'Groom', 'Sleep', 'Grumpy', 'Stretch')

def teacher(x):
    energy, sleepy, irritated, stimulated, near, motion, clicks, idle, panel, affection, age, roam = x.T
    wave = near * motion
    scores = np.array([
        1.3 + .3*near - 1.4*sleepy - .8*stimulated - irritated,
        .2 + 2.4*roam + .7*idle + .6*energy - 2.5*sleepy - 2*irritated - .8*stimulated,
        -2 + 5*wave + 2*stimulated + energy - 2.3*sleepy - 3*irritated,
        -1 + 3.7*near + 1.2*wave + .8*clicks + .8*stimulated - .8*sleepy - 2*irritated,
        -1.5 + 4.5*panel + roam + stimulated - .6*near - 2*sleepy - 2*irritated,
        -3.5 + 9.5*stimulated + 2*energy + .7*motion - 4*irritated - 4*sleepy,
        .3 + 2*idle + affection - 1.6*roam - 4*stimulated - 3*irritated - 1.5*wave,
        -2.8 + 7*sleepy + 3*(1-energy) + idle - 5*stimulated - 2*clicks - irritated,
        -2.8 + 7.5*irritated + .6*clicks - .4*affection,
        -.5 + 2*np.maximum(0, 1-np.abs(sleepy-.3)/.3) + .8*idle - .6*roam - 3*stimulated - 2*irritated + .2*age,
    ]).T
    scores -= scores.max(axis=1, keepdims=True)
    probabilities = np.exp(scores / .85)
    return probabilities / probabilities.sum(axis=1, keepdims=True)

def examples(rng, count):
    x = rng.random((count, 12))
    # Half the examples resemble the app's usual calm/interacting state rather
    # than the less likely simultaneous maximum of all internal needs.
    calm = count//2
    x[:calm, 2:4] *= .35
    x[:calm, 6] *= .3
    x[:calm, 8] = rng.choice([0., 1.], calm)
    x[:calm, 4:6] = rng.choice([0., 1.], (calm, 2))
    return x

def main():
    rng = np.random.default_rng(SEED)
    x = examples(rng, 16000)
    labels = teacher(x)
    inputs = x*2-1
    parameters = [rng.normal(0, .22, (12, 16)), np.zeros(16), rng.normal(0, .22, (16, 10)), np.zeros(10)]
    first = [np.zeros_like(p) for p in parameters]
    second = [np.zeros_like(p) for p in parameters]
    step = 0
    for epoch in range(380):
        for batch in np.array_split(rng.permutation(len(x)), 40):
            a = inputs[batch]
            target = labels[batch]
            w1, b1, w2, b2 = parameters
            hidden = np.tanh(a @ w1 + b1)
            logits = hidden @ w2 + b2
            logits -= logits.max(axis=1, keepdims=True)
            prediction = np.exp(logits)
            prediction /= prediction.sum(axis=1, keepdims=True)
            error = (prediction-target)/len(batch)
            hidden_error = (error @ w2.T)*(1-hidden*hidden)
            gradients = [a.T@hidden_error, hidden_error.sum(axis=0), hidden.T@error, error.sum(axis=0)]
            step += 1
            for i, gradient in enumerate(gradients):
                first[i] = .9*first[i] + .1*gradient
                second[i] = .999*second[i] + .001*gradient*gradient
                parameters[i] -= .006*(first[i]/(1-.9**step))/(np.sqrt(second[i]/(1-.999**step))+1e-8)
    validation = examples(np.random.default_rng(SEED+1), 4000)
    hidden = np.tanh((validation*2-1)@parameters[0]+parameters[1])
    logits = hidden@parameters[2]+parameters[3]
    targets = teacher(validation)
    agreement = np.mean(np.argmax(logits,axis=1) == np.argmax(targets,axis=1))
    assert agreement > .90, f'Unexpectedly weak policy agreement: {agreement:.3%}'
    destination = Path(__file__).resolve().parent.parent/'src/BabbleFrameBridge.App/KittyModel.cs'
    lines = ['// Copyright (c) 2026 Frame Bridge contributors.', '// SPDX-License-Identifier: Apache-2.0',
        '// Generated by tools/train_kitty_policy.py; original synthetic examples only.',
        f'// Seed {SEED}; 12 input -> 16 tanh -> 10 softmax; 378 parameters.',
        f'// Held-out top-action agreement: {agreement:.2%} (4,000 original synthetic scenarios).',
        'namespace BabbleFrameBridge.App;', 'internal static class KittyModel', '{']
    for name, array in zip(('InputWeights','HiddenBias','OutputWeights','OutputBias'), parameters):
        lines.append('    internal static readonly double[] '+name+' =')
        lines.append('    [')
        flat = array.ravel()
        for start in range(0, len(flat), 8):
            lines.append('        '+', '.join(format(float(value), '.9g') for value in flat[start:start+8])+',')
        lines.append('    ];')
    lines.extend(['}', ''])
    destination.write_text('\n'.join(lines), encoding='utf-8')
    print(f'Generated {destination.name}: 378 parameters, 3,024 numerical bytes; held-out agreement {agreement:.2%}.')

if __name__ == '__main__':
    main()
